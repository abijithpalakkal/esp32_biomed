import { Pool } from "pg";
import { createClient } from "@supabase/supabase-js";

const rawDatabaseUrl = (process.env.DATABASE_URL || "")
  .trim()
  .replace(/^["']|["']$/g, "");
export const isPostgresConfigured = Boolean(
  rawDatabaseUrl &&
  !rawDatabaseUrl.includes("[YOUR-PASSWORD]") &&
  !rawDatabaseUrl.includes("YOUR-PASSWORD") &&
  !rawDatabaseUrl.includes("your-password")
);

// ─── 2. Supabase REST API Config ─────────────────────────────────────────────
const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || "";

export const isSupabaseRestConfigured = Boolean(
  supabaseUrl &&
  supabaseAnonKey &&
  supabaseUrl !== "https://your-project.supabase.co" &&
  !supabaseUrl.includes("your-project") &&
  supabaseAnonKey !== "your-anon-key-here"
);

export const isDbConfigured = isPostgresConfigured || isSupabaseRestConfigured;

// ─── Connection Pool for PostgreSQL (Singleton in dev) ───────────────────────
declare global {
  // eslint-disable-next-line no-var
  var pgPool: Pool | undefined;
}

let pool: Pool | null = null;
if (isPostgresConfigured) {
  if (!globalThis.pgPool) {
    globalThis.pgPool = new Pool({
      connectionString: rawDatabaseUrl,
      ssl: rawDatabaseUrl.includes("supabase.co") ? { rejectUnauthorized: false } : undefined,
      max: 10,
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 10000,
    });
  }
  pool = globalThis.pgPool;
}

// ─── Supabase REST Client ────────────────────────────────────────────────────
export const supabaseClient = isSupabaseRestConfigured
  ? createClient(supabaseUrl, supabaseAnonKey)
  : null;

// Ensure table and columns exist on first query (for direct PostgreSQL connection)
let tableEnsured = false;
async function ensureTable() {
  if (tableEnsured || !pool) return;
  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS public.temperature_readings (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        temperature REAL NOT NULL,
        heart_rate INTEGER,
        spo2 INTEGER,
        created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
      );
      ALTER TABLE public.temperature_readings ADD COLUMN IF NOT EXISTS heart_rate INTEGER;
      ALTER TABLE public.temperature_readings ADD COLUMN IF NOT EXISTS spo2 INTEGER;
      CREATE INDEX IF NOT EXISTS idx_temperature_readings_created_at
        ON public.temperature_readings (created_at DESC);
    `);
    tableEnsured = true;
  } catch (err) {
    console.warn("[DB] Could not ensure table exists:", err);
  }
}

export interface DbTempRecord {
  id?: number | string;
  temperature: number;
  heart_rate?: number | null;
  spo2?: number | null;
  created_at: string;
}

export async function insertTemperatureReading(
  temp: number,
  timestamp: string,
  heartRate?: number | null,
  spo2?: number | null
): Promise<DbTempRecord | null> {
  const hrVal = heartRate != null && !isNaN(heartRate) && heartRate > 0 ? Math.round(heartRate) : null;
  const spo2Val = spo2 != null && !isNaN(spo2) && spo2 > 0 ? Math.round(spo2) : null;

  if (isPostgresConfigured && pool) {
    try {
      await ensureTable();
      const result = await pool.query(
        `INSERT INTO public.temperature_readings (temperature, heart_rate, spo2, created_at)
         VALUES ($1, $2, $3, $4)
         RETURNING id, temperature, heart_rate, spo2, created_at`,
        [temp, hrVal, spo2Val, timestamp]
      );
      if (result.rows.length > 0) {
        const row = result.rows[0];
        return {
          id: row.id,
          temperature: Number(row.temperature),
          heart_rate: row.heart_rate != null ? Number(row.heart_rate) : null,
          spo2: row.spo2 != null ? Number(row.spo2) : null,
          created_at: new Date(row.created_at).toISOString(),
        };
      }
    } catch (pgErr) {
      console.error("[DB] PostgreSQL insert error:", pgErr);
    }
  } else if (isSupabaseRestConfigured && supabaseClient) {
    try {
      const { data, error } = await supabaseClient
        .from("temperature_readings")
        .insert([{
          temperature: temp,
          heart_rate: hrVal,
          spo2: spo2Val,
          created_at: timestamp
        }])
        .select()
        .single();
      if (!error && data) {
        return {
          id: data.id,
          temperature: Number(data.temperature),
          heart_rate: data.heart_rate != null ? Number(data.heart_rate) : null,
          spo2: data.spo2 != null ? Number(data.spo2) : null,
          created_at: data.created_at,
        };
      }
      if (error) {
        console.warn("[DB] Supabase REST insert error:", error.message);
      }
    } catch (sbErr) {
      console.error("[DB] Supabase REST error:", sbErr);
    }
  }

  return null;
}

export async function getTemperatureReadings(limit: number): Promise<DbTempRecord[] | null> {
  if (isPostgresConfigured && pool) {
    try {
      await ensureTable();
      const result = await pool.query(
        `SELECT id, temperature, heart_rate, spo2, created_at
         FROM public.temperature_readings
         ORDER BY created_at DESC
         LIMIT $1`,
        [limit]
      );
      return result.rows.map((row) => ({
        id: row.id,
        temperature: Number(row.temperature),
        heart_rate: row.heart_rate != null ? Number(row.heart_rate) : null,
        spo2: row.spo2 != null ? Number(row.spo2) : null,
        created_at: new Date(row.created_at).toISOString(),
      }));
    } catch (pgErr) {
      console.error("[DB] PostgreSQL fetch error:", pgErr);
      return null;
    }
  } else if (isSupabaseRestConfigured && supabaseClient) {
    try {
      const { data, error } = await supabaseClient
        .from("temperature_readings")
        .select("id, temperature, heart_rate, spo2, created_at")
        .order("created_at", { ascending: false })
        .limit(limit);
      if (!error && data) {
        return data.map((item) => ({
          id: item.id,
          temperature: Number(item.temperature),
          heart_rate: item.heart_rate != null ? Number(item.heart_rate) : null,
          spo2: item.spo2 != null ? Number(item.spo2) : null,
          created_at: item.created_at,
        }));
      }
    } catch (sbErr) {
      console.error("[DB] Supabase REST error:", sbErr);
      return null;
    }
  }

  return null;
}
