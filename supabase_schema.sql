-- Run this SQL in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)

-- ==============================================================================
-- 1. UPGRADE EXISTING TABLE (If you already have temperature_readings table)
-- ==============================================================================
alter table public.temperature_readings 
  add column if not exists heart_rate integer,
  add column if not exists spo2 integer;

-- ==============================================================================
-- 2. FULL TABLE CREATION (For new installations)
-- ==============================================================================
create table if not exists public.temperature_readings (
  id bigint generated by default as identity primary key,
  temperature float4 not null,
  heart_rate integer,
  spo2 integer,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- 3. INDEX FOR FAST CHRONOLOGICAL QUERIES
-- ==============================================================================
create index if not exists idx_temperature_readings_created_at
  on public.temperature_readings (created_at desc);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- ==============================================================================
alter table public.temperature_readings enable row level security;

-- Allow public read access (for Next.js frontend / API)
drop policy if exists "Allow public read access" on public.temperature_readings;
create policy "Allow public read access"
  on public.temperature_readings
  for select
  to anon, authenticated
  using (true);

-- Allow public insert (for Next.js API / ESP32)
drop policy if exists "Allow public insert" on public.temperature_readings;
create policy "Allow public insert"
  on public.temperature_readings
  for insert
  to anon, authenticated
  with check (true);
